// Writes src/protocol.ts and src/operations.ts from wardrik_protocol's priv/v1: the types of
// every schema, and a method for every operation openapi.json defines. With --check, fails
// instead where either file is not what the protocol makes.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { compile, type JSONSchema } from "json-schema-to-typescript";
import { format } from "prettier";

const schemas = new URL(process.env.WARDRIK_PROTOCOL ?? "../../wardrik_protocol/priv/v1/", import.meta.url);
const urn = "urn:wardrik:schema:v1:";
const defsRef = urn + "defs#/$defs/";

type Schema = { [key: string]: any };

const read = (file: string): Schema => JSON.parse(readFileSync(new URL(file, schemas), "utf8")) as Schema;

const pascal = (text: string): string =>
  text
    .split(/[._]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");

const camel = (text: string): string => {
  const name = pascal(text);
  return name.charAt(0).toLowerCase() + name.slice(1);
};

const files = readdirSync(schemas).filter((file) => file.endsWith(".json")).sort();
const events = files.filter((file) => /^[a-z_]+\.[a-z_]+\.json$/.test(file)).map((file) => file.slice(0, -5));
const defs = read("defs.json")["$defs"] as Record<string, Schema>;

// A resource is any schema that is neither an event's data, the shared definitions, nor the
// document. Two are renamed: one whose name the SDK's own class takes, and the envelope.
const renamed: Record<string, string> = { agent: "AgentSummary", cloudevent: "CloudEvent" };

const resources = files
  .map((file) => file.slice(0, -5))
  .filter((name) => !name.includes(".") && name !== "defs" && name !== "openapi");

const defTitle = (name: string): string => (name === "error" ? "ErrorInfo" : pascal(name));

const resourceTitle = (name: string): string =>
  renamed[name] ?? (name in defs ? pascal(name) + "Body" : pascal(name));

const eventTitle = (type: string): string => pascal(type) + "Data";

// The title of the type a reference names.
const titleOf = (ref: string): string => {
  if (ref.startsWith(defsRef)) return defTitle(ref.slice(defsRef.length));
  const name = ref.slice(urn.length);
  if (events.includes(name)) return eventTitle(name);
  if (resources.includes(name)) return resourceTitle(name);
  throw new Error(`No schema is ${ref}`);
};

// Points each reference at the one root's $defs, and drops what only a validator reads.
const local = (node: unknown): unknown => {
  if (Array.isArray(node)) return node.map(local);
  if (node === null || typeof node !== "object") return node;

  const ref = (node as Schema)["$ref"];
  if (typeof ref === "string" && ref.startsWith(urn)) return { $ref: "#/$defs/" + titleOf(ref) };

  const out: Schema = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "$schema" || key === "$id" || key === "examples") continue;
    out[key] = local(value);
  }
  return out;
};

const $defs: Record<string, unknown> = {};
for (const [name, schema] of Object.entries(defs)) $defs[defTitle(name)] = { ...(local(schema) as Schema), title: defTitle(name) };
for (const name of resources) $defs[resourceTitle(name)] = { ...(local(read(name + ".json")) as Schema), title: resourceTitle(name) };
for (const type of events) $defs[eventTitle(type)] = { ...(local(read(type + ".json")) as Schema), title: eventTitle(type) };

const banner = (what: string) => `// Generated by scripts/generate.ts from wardrik_protocol's priv/v1${what}. Do not edit.
// Run \`npm run generate\` after the protocol changes.`;

const compiled = await compile({ title: "Protocol", type: "object", additionalProperties: false, $defs } as JSONSchema, "Protocol", {
  bannerComment: banner(""),
  ignoreMinAndMaxItems: true,
  unreachableDefinitions: true,
  additionalProperties: false,
  format: true,
  style: { printWidth: 100 },
});

const eventMap = events.map((type) => `  "wardrik.${type}": ${eventTitle(type)};`).join("\n");

const referenced = / \*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n/g;
const alone = /\/\*\*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g;

const protocol =
  compiled.replace(alone, "").replace(referenced, "").replace(/export interface Protocol \{\}\n\n?/, "") +
  `
/** Each event type, and the data its events carry. */
export interface EventData {
${eventMap}
}

/** An event's type, as its CloudEvent names it. */
export type EventType = keyof EventData;

/** A Wardrik event: a CloudEvent whose data is its type's. */
export type WardrikEvent = {
  [T in EventType]: Omit<CloudEvent, "type" | "data"> & { type: T; data: EventData[T] };
}[EventType];

/** The event of one type. */
export type EventOf<T extends EventType> = Extract<WardrikEvent, { type: T }>;
`;

// The operations, each read once from the document.

const openapi = read("openapi.json");
const parameters = openapi.components.parameters as Record<string, Schema>;

// Operations a token calls. Hooks and channels are answered for the services that post to them.
const offered = (subject: string): boolean => subject !== "hook" && subject !== "channel";

interface Param {
  name: string;
  in: "path" | "query";
  required: boolean;
  type: string;
  description: string | undefined;
}

interface Operation {
  id: string;
  method: string;
  path: string;
  summary: string;
  description: string | undefined;
  params: Param[];
  body: string | undefined;
  bodyRequired: boolean;
  output: string | undefined;
  unwrap: string | undefined;
  stream: boolean;
}

const tsType = (schema: Schema): string => {
  if (schema.enum) return schema.enum.map((value: unknown) => JSON.stringify(value)).join(" | ");
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "array") return `${tsType(schema.items)}[]`;
  return "string";
};

const param = (node: Schema): Param => {
  const spec = node.$ref ? parameters[node.$ref.replace("#/components/parameters/", "")]! : node;
  return {
    name: spec.name,
    in: spec.in,
    required: spec.required ?? false,
    type: tsType(spec.schema),
    description: spec.description,
  };
};

// The schema a response's JSON body is, or undefined where it has none.
const answered = (operation: Schema): Schema | undefined => {
  const [, response] = Object.entries(operation.responses as Record<string, Schema>).find(([code]) => code.startsWith("2"))!;
  return response.content?.["application/json"]?.schema;
};

// An answer of one property is that property: `{agents: [...]}` is the list.
const unwrapped = (schema: Schema | undefined): string | undefined => {
  if (!schema?.$ref) return undefined;
  const keys = Object.keys(read(schema.$ref.slice(urn.length) + ".json").properties ?? {});
  return keys.length === 1 ? keys[0] : undefined;
};

const bodyRequired = (ref: string, required: boolean): boolean => {
  const schema = read(ref.slice(urn.length) + ".json");
  return required && ((schema.required ?? []).length > 0 || "oneOf" in schema || "anyOf" in schema);
};

const operations: Operation[] = [];

for (const [path, methods] of Object.entries(openapi.paths as Record<string, Schema>)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!offered(operation["x-wardrik-subject"])) continue;

    const output = answered(operation);
    const body = operation.requestBody?.content["application/json"].schema.$ref as string | undefined;
    const ok = Object.entries(operation.responses as Record<string, Schema>).find(([code]) => code.startsWith("2"))![1];

    operations.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      summary: operation.summary,
      description: operation.description,
      params: (operation.parameters ?? []).map(param),
      body: body && titleOf(body),
      bodyRequired: body ? bodyRequired(body, operation.requestBody.required ?? false) : false,
      output: output?.$ref && titleOf(output.$ref),
      unwrap: unwrapped(output),
      stream: "text/event-stream" in (ok.content ?? {}),
    });
  }
}

const pathParams = (operation: Operation): Param[] =>
  [...operation.path.matchAll(/\{([a-z_]+)\}/g)].map(([, name]) => operation.params.find((param) => param.name === name)!);

const queryParams = (operation: Operation): Param[] => operation.params.filter((param) => param.in === "query");

const field = (param: Param): string => {
  const doc = param.description ? `  /** ${param.description} */\n` : "";
  return `${doc}  ${param.name}${param.required ? "" : "?"}: ${param.type}${param.required ? "" : " | undefined"};`;
};

const fields = (params: Param[]): string => (params.length === 0 ? "{}" : `{\n${params.map(field).join("\n")}\n}`);

const inputType = (operation: Operation, params: Param[]): string => {
  const parts = [...(params.length > 0 ? [fields(params)] : []), ...(operation.body ? [operation.body] : [])];
  return parts.length === 0 ? "{}" : parts.join(" & ");
};

const outputType = (operation: Operation): string => {
  if (operation.output === undefined) return "void";
  if (operation.unwrap === undefined) return operation.output;
  return `${operation.output}[${JSON.stringify(operation.unwrap)}]`;
};

const required = (operation: Operation, params: Param[]): boolean =>
  params.some((param) => param.required) || operation.bodyRequired;

const table = operations
  .map((operation) => {
    const entry = {
      method: operation.method,
      path: operation.path,
      path_params: pathParams(operation).map((param) => param.name),
      query: queryParams(operation).map((param) => param.name),
      body: operation.body !== undefined,
      ...(operation.unwrap ? { unwrap: operation.unwrap } : {}),
      ...(operation.stream ? { stream: true } : {}),
    };
    return `  ${JSON.stringify(operation.id)}: ${JSON.stringify(entry)},`;
  })
  .join("\n");

const inputs = operations
  .map((operation) => `  ${JSON.stringify(operation.id)}: ${inputType(operation, operation.params)};`)
  .join("\n");

const outputs = operations.map((operation) => `  ${JSON.stringify(operation.id)}: ${outputType(operation)};`).join("\n");

const doc = (operation: Operation, indent: string): string => {
  const lines = [operation.summary + ".", ...(operation.description ? ["", operation.description] : [])];
  return `${indent}/**\n${lines.map((line) => `${indent} *${line ? " " + line : ""}`).join("\n")}\n${indent} */\n`;
};

// A method of a namespace: path parameters by position, but those `bound` to the namespace,
// then the rest of the input as one object.
const signature = (operation: Operation, bound: string[], query: Param[]) => {
  const positional = pathParams(operation).filter((param) => !bound.includes(param.name));
  const rest = inputType(operation, query);
  const args = positional.map((param) => `${camel(param.name)}: string`);

  if (rest !== "{}") args.push(`input: ${rest}${required(operation, query) ? "" : " = {}"}`);

  const assigned = [
    ...(rest !== "{}" ? ["...input"] : []),
    ...bound.filter((name) => operation.path.includes(`{${name}}`)).map((name) => `${name}: this.${camel(name)}`),
    ...positional.map((param) => (param.name === camel(param.name) ? param.name : `${param.name}: ${camel(param.name)}`)),
  ];

  return { args, value: assigned.length === 0 ? "{}" : `{ ${assigned.join(", ")} }` };
};

const call = (operation: Operation, name: string, bound: string[]): string => {
  const { args, value } = signature(operation, bound, queryParams(operation));
  const id = JSON.stringify(operation.id);

  return (
    doc(operation, "  ") +
    `  ${name}(${[...args, "options: CallOptions = {}"].join(", ")}): Promise<Outputs[${id}]> {\n` +
    `    return this.#runner.call(${id}, ${value}, options);\n  }\n`
  );
};

// A streamed operation's events as an EventStream, which follows the log and reconnects.
const stream = (operation: Operation, name: string, bound: string[]): string => {
  const query = queryParams(operation).filter((param) => param.name !== "limit");
  const { args, value } = signature(operation, bound, query);

  return (
    `  /**\n   * Streams what \`${operation.id}\` reads, then each new event as it's written. Starts after\n` +
    `   * \`after\`, or at the end of the log. See \`EventStream\`.\n   */\n` +
    `  ${name}(${[...args, "options: StreamOptions = {}"].join(", ")}): EventStream {\n` +
    `    return this.#runner.stream(${JSON.stringify(operation.id)}, ${value}, options);\n  }\n`
  );
};

const method = (operation: Operation, prefix: string, bound: string[]): string => {
  const verb = operation.id.slice(prefix.length + 1);
  const called = call(operation, camel(verb), bound);
  return operation.stream ? called + "\n" + stream(operation, "stream" + pascal(verb), bound) : called;
};

const prefixes = [...new Set(operations.map((operation) => operation.id.split(".")[0]!))];

const namespace = (prefix: string): string => {
  const bound = prefix === "agent" ? ["agent"] : [];
  const methods = operations
    .filter((operation) => operation.id.startsWith(prefix + "."))
    .map((operation) => method(operation, prefix, bound))
    .join("\n");

  const field = prefix === "agent" ? "  /** The agent's ID, as acme/triage or acme/@jon/triage. */\n  readonly agent: string;\n" : "";
  const init = prefix === "agent" ? "    this.agent = agent;\n" : "";
  const args = prefix === "agent" ? "runner: Runner, agent: string" : "runner: Runner";

  return (
    `/** The \`${prefix}.*\` operations. */\nexport class ${pascal(prefix)}Operations {\n${field}  readonly #runner: Runner;\n\n` +
    `  /** @internal */\n  constructor(${args}) {\n    this.#runner = runner;\n${init}  }\n\n${methods}}\n`
  );
};

const grouped = prefixes.filter((prefix) => prefix !== "agent");

const types = [
  ...new Set(
    operations.flatMap((operation) => [operation.body, operation.output].filter((name): name is string => name !== undefined)),
  ),
].sort();

const operationsFile = `${banner(" openapi.json")}

import type { EventStream } from "./events.ts";
import type { CallOptions, Runner, StreamOptions } from "./runner.ts";
import type {
${types.map((name) => `  ${name},`).join("\n")}
} from "./protocol.ts";

/** Where each operation is served, and how its input travels. */
export const operations = {
${table}
} as const;

/** An operation's id, as \`agent.ask\`. */
export type OperationId = keyof typeof operations;

/** What each operation takes: its path and query parameters and its body, as one object. */
export interface Inputs {
${inputs}
}

/** What each operation answers, an answer of one property being that property. */
export interface Outputs {
${outputs}
}

${namespace("agent")}
${grouped.map(namespace).join("\n")}
/** Every operation but an agent's, by its namespace. */
export class Operations {
${grouped.map((prefix) => `  /** The \`${prefix}.*\` operations. */\n  readonly ${camel(prefix)}: ${pascal(prefix)}Operations;`).join("\n")}

  /** @internal */
  constructor(runner: Runner) {
${grouped.map((prefix) => `    this.${camel(prefix)} = new ${pascal(prefix)}Operations(runner);`).join("\n")}
  }
}
`;

const targets: [URL, string][] = [
  [new URL("../src/protocol.ts", import.meta.url), protocol],
  [new URL("../src/operations.ts", import.meta.url), await format(operationsFile, { parser: "typescript", printWidth: 100 })],
];

if (process.argv.includes("--check")) {
  const stale = targets.filter(([target, output]) => readFileSync(target, "utf8") !== output);
  for (const [target] of stale) console.error(`${target.pathname} is out of date; run \`npm run generate\`.`);
  if (stale.length > 0) process.exit(1);
} else {
  for (const [target, output] of targets) writeFileSync(target, output);
}
